"""Load the cleaned data into SQLite and run every query in sql/business_questions.sql.
Results are printed and saved to reports/sql_results.md."""
from pathlib import Path
import re
import sqlite3

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "processed" / "listings_clean.csv"
SQL_FILE = ROOT / "sql" / "business_questions.sql"
DB = ROOT / "data" / "processed" / "berlin_airbnb.db"
REPORT = ROOT / "reports" / "sql_results.md"


def split_queries(sql_text: str):
    """Yield (title, query) pairs; the title is the '-- Qn.' comment above each query."""
    for block in sql_text.split(";"):
        title = re.search(r"--\s*(Q\d+\..*)", block)
        query = "\n".join(l for l in block.splitlines() if not l.strip().startswith("--")).strip()
        if query:
            yield (title.group(1).strip() if title else "Query"), query


def main() -> None:
    df = pd.read_csv(DATA)
    with sqlite3.connect(DB) as conn:
        df.to_sql("listings", conn, if_exists="replace", index=False)
        sections = ["# SQL results\n", f"_Generated by `src/run_sql.py` from `{SQL_FILE.name}`_\n"]
        for title, query in split_queries(SQL_FILE.read_text(encoding="utf-8")):
            result = pd.read_sql_query(query, conn)
            print(f"\n{title}\n{result.to_string(index=False)}")
            sections.append(f"\n## {title}\n\n```sql\n{query}\n```\n\n{result.to_markdown(index=False)}\n")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(sections), encoding="utf-8")
    print(f"\nSaved {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
